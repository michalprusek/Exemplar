#!/usr/bin/env python3
# Copied from AutoSeg scripts/make_timing_numbers.py (cb71f85) by tools/sync_paper.py; default paths adapted, internal notes rewritten in comments and docstrings.
"""Emit every timing number the paper states, as macros, from results/timing_a5000.json.

WHY THIS EXISTS. The accuracy tables and the statistics have been script-generated for months, but
the latency numbers -- which carry one of the paper's two main claims -- were typed straight into
main.tex. Nothing in the repository could reproduce them, so nothing could contradict them either,
and three of them turned out to be wrong at once: the fit range had no provenance, the per-image
figure was out by two orders of magnitude because it timed the head at feature resolution while the
model emits a native-resolution mask, and nnU-Net's cost was both the wrong value and wrongly
claimed to be independent of field size. A number no script can regenerate is a number no one
checks.

The ratio is deliberately computed from the LOWER bound on nnU-Net's largest field, which did not
finish inside its cap. That makes the reported speed-up conservative in nnU-Net's favour: the true
ratio is larger. Rounding is toward the less flattering value for the same reason.

  ASG_TIMING=results/timing_a5000.json ASG_SEM_OUT=paper/isbi2027 python scripts/make_timing_numbers.py
"""
import json
import math
import os
import sys

SRC = os.environ.get("ASG_TIMING", "results/timing_a5000.json")
OUT = os.environ.get("ASG_SEM_OUT", "paper/out")
# ASG_TIMING_OURS: our rows from another record (the method of 2026-10-14), nnU-Net's still from SRC.
# ASG_TIMING_CP: fine-tuned Cellpose-SAM's fit times, for the cost against the strongest specialist.
OURS_SRC = os.environ.get("ASG_TIMING_OURS")
CP_SRC = os.environ.get("ASG_TIMING_CP")

# ASG_TIMING_PENDING=1: for a run before the timing measurement has finished. Every timing macro
# prints a visible placeholder, never another method's number, and audit_paper_numbers refuses the file.
if os.environ.get("ASG_TIMING_PENDING") == "1":
    names = ["fitSmall", "fitLarge", "fitDrawLo", "fitDrawHi", "encLo", "encHi", "maskLo", "maskHi", "encLargeS",
             "nnSmall", "nnLarge", "costRatioLo", "costRatioHi", "cpFitSmall", "cpFitLarge", "cpRatioLo", "cpRatioHi"]
    lines = ["% Generated by scripts/make_timing_numbers.py. PENDING: the timing of the reported method is still running."]
    lines += [f"\\newcommand{{\\{n}}}{{\\textbf{{??}}}}" for n in names]
    open(os.path.join(OUT, "numbers_timing.tex"), "w").write("\n".join(lines) + "\n")
    print("wrote PENDING placeholders"); sys.exit(0)

with open(SRC) as fh:
    d = json.load(fh)
src_ours = json.load(open(OURS_SRC)) if OURS_SRC else d

ours = sorted(src_ours["ours"], key=lambda r: r["side_px"])
nn = {r["dataset"]: r for r in d["nnunet"]}
small, large = ours[0], ours[-1]

if src_ours.get("fit_only"):
    # The closed-form ridge: fit and refit times only (no per-image prediction time from this record). nnU-Net and
    # Cellpose-SAM against the cold fit, as before.
    cp = {r["dataset"]: r for r in json.load(open(CP_SRC))["rows"]} if CP_SRC else {}
    for r in ours:
        if r.get("fit_s") is None or r.get("refit_s") is None:
            sys.exit(f"REFUSING: {r['dataset']} has no fit_s or refit_s")
    lines = [f"% Generated by scripts/make_timing_numbers.py from {OURS_SRC} (nnU-Net from {SRC}"
             + (f", Cellpose-SAM from {CP_SRC}" if CP_SRC else "") + "). Do not hand-edit.",
             f"% Measured on one {src_ours['device']}, {src_ours['date']}.",
             f"\\newcommand{{\\fitSmall}}{{{small['fit_s']['median']:.0f}}}",
             f"\\newcommand{{\\fitLarge}}{{{large['fit_s']['median']:.0f}}}",
             # refit: one decimal below ten seconds, whole seconds above
             f"\\newcommand{{\\refitSmall}}{{{small['refit_s']['median']:.1f}}}",
             f"\\newcommand{{\\refitLarge}}{{{large['refit_s']['median']:.0f}}}",
             f"\\newcommand{{\\costRatioLo}}{{{math.floor(nn['hrf']['fit_s'] / large['fit_s']['median'])}}}",
             f"\\newcommand{{\\costRatioHi}}{{{math.floor(nn['dsb2018']['fit_s'] / small['fit_s']['median'])}}}",
             f"\\newcommand{{\\nnSmallMin}}{{{math.floor(nn['dsb2018']['fit_s'] / 60)}}}",
             # the coarse reading of one image (672-px input, the same backbone), measured on the same card (in
             # float32 there; the ridge runs the backbone in bfloat16, so this is an upper bound)
             f"\\newcommand{{\\encHi}}{{{max(r['encode_ms'] for r in d['ours'])}}}",
             f"\\newcommand{{\\nnLargeMin}}{{{math.floor(nn['hrf']['fit_s'] / 60)}}}"]
    if cp:
        if small["dataset"] not in cp or large["dataset"] not in cp:
            sys.exit(f"REFUSING: Cellpose-SAM timing lacks {small['dataset']} or {large['dataset']}")
        cs, cl = cp[small["dataset"]]["fit_s"]["median"], cp[large["dataset"]]["fit_s"]["median"]
        lines += [f"\\newcommand{{\\cpFitSmall}}{{{math.floor(cs / 60)}}}",
                  f"\\newcommand{{\\cpFitLarge}}{{{math.floor(cl / 60)}}}",
                  f"\\newcommand{{\\cpRatioLo}}{{{math.floor(cl / large['fit_s']['median'])}}}",
                  f"\\newcommand{{\\cpRatioHi}}{{{math.floor(cs / small['fit_s']['median'])}}}",
                  f"% Cellpose-SAM fine-tune medians {cs:.0f} s ({small['dataset']}), {cl:.0f} s ({large['dataset']})"]
    cpr_dir = os.environ.get("ASG_TIMING_CPREFIT")
    if cp and not cpr_dir:
        # Cellpose-SAM's warm refit for an eighth of its 800-epoch budget, as an eighth of its fine-tune measured on an
        # IDLE A5000: a lower bound in its favour (the per-call preparation is paid once in either). Used because
        # the direct refit timing shared the card with another user's jobs.
        lines += [f"\\newcommand{{\\cpRefitSmall}}{{{math.floor(cs / 8)}}}",
                  f"\\newcommand{{\\cpRefitLarge}}{{{math.floor(cl / 8)}}}",
                  "% Cellpose-SAM refit (100 of 800 epochs) = fine-tune time / 8, a lower bound"]
    if cpr_dir:
        # Cellpose-SAM's warm refit 7->8 (scripts/c114/cellpose_refit.py --stage refit), on
        # the same card: median over the draws, whole seconds, at the two ends of the field range.
        import statistics
        cpr = {ds: json.load(open(os.path.join(cpr_dir, f"refit__{ds}.json"))) for ds in (small["dataset"], large["dataset"])}
        for ds, r in cpr.items():
            if r["device"] != src_ours["device"]:
                sys.exit(f"REFUSING: Cellpose-SAM refit on {r['device']}, ours on {src_ours['device']}")
        med = {ds: statistics.median(r["fit_s"]) for ds, r in cpr.items()}
        lines += [f"\\newcommand{{\\cpRefitSmall}}{{{med[small['dataset']]:.0f}}}",
                  f"\\newcommand{{\\cpRefitLarge}}{{{med[large['dataset']]:.0f}}}",
                  f"% Cellpose-SAM warm refit {cpr[small['dataset']]['refit_epochs']} epochs: "
                  + ", ".join(f"{ds} {med[ds]:.1f} s" for ds in med)]
    spec_src = os.environ.get("ASG_TIMING_SPEC")
    if spec_src:
        # Fine-tuned StarDist and micro-SAM (scripts/c114/spec_ft_timing.py: the training call
        # only, at Table 1's training length) for Table 1's fit-time row. Minutes rounded DOWN, as Cellpose-SAM's, so the
        # rounding favours them; one decimal below ten minutes, where a whole minute would hide a fifth of the time.
        def minutes(s):
            return f"{math.floor(s / 6) / 10:.1f}" if s < 600 else f"{math.floor(s / 60)}"
        length = {"StarDist": 1600, "micro-SAM": 50}
        spec = json.load(open(spec_src))["rows"]
        for meth, stem in (("StarDist", "sd"), ("micro-SAM", "ms")):
            rows = {r["dataset"]: r for r in spec if r["method"] == meth}
            for ds in (small["dataset"], large["dataset"]):
                r = rows.get(ds)
                if r is None:
                    sys.exit(f"REFUSING: {spec_src} has no {meth} row on {ds}")
                if r["device"] != src_ours["device"] or r["epochs"] != length[meth] or len(r["fit_s_all"]) < 3:
                    sys.exit(f"REFUSING: {meth} {ds} on {r['device']}, {r['epochs']} epochs, "
                             f"{len(r['fit_s_all'])} draws (need {src_ours['device']}, {length[meth]}, 3)")
            lines += [f"\\newcommand{{\\{stem}FitSmall}}{{{minutes(rows[small['dataset']]['fit_s'])}}}",
                      f"\\newcommand{{\\{stem}FitLarge}}{{{minutes(rows[large['dataset']]['fit_s'])}}}",
                      f"% {meth} fine-tune medians {rows[small['dataset']]['fit_s']} s ({small['dataset']}), "
                      f"{rows[large['dataset']]['fit_s']} s ({large['dataset']}), from {spec_src}"]
    cvp_src = os.environ.get("ASG_TIMING_CVP")
    if cvp_src:
        # Convpaint: the training call, feature extractor on the GPU; per dataset the FASTER of CatBoost on the CPU and
        # on the GPU, minutes rounded DOWN like the specialists', both in Convpaint's favour. Rows of
        # convpaint_<ds>.json, merged.
        def minutes_c(s):
            return f"{math.floor(s / 6) / 10:.1f}" if s < 600 else f"{math.floor(s / 60)}"
        crow = {}
        for r in json.load(open(cvp_src))["rows"]:
            if r["method"] != "Convpaint" or r["device"] != src_ours["device"] or len(r["fit_s_all"]) < 3:
                continue
            if r["dataset"] not in crow or r["fit_s"] < crow[r["dataset"]]["fit_s"]:
                crow[r["dataset"]] = r
        for ds in (small["dataset"], large["dataset"]):
            if ds not in crow:
                sys.exit(f"REFUSING: {cvp_src}: no Convpaint row on {ds} on {src_ours['device']} with 3 draws")
        lines += [f"\\newcommand{{\\cvpFitSmall}}{{{minutes_c(crow[small['dataset']]['fit_s'])}}}",
                  f"\\newcommand{{\\cvpFitLarge}}{{{minutes_c(crow[large['dataset']]['fit_s'])}}}",
                  f"% Convpaint fit medians {crow[small['dataset']]['fit_s']} s ({small['dataset']}, CatBoost on "
                  f"{crow[small['dataset']].get('clf_device')}), {crow[large['dataset']]['fit_s']} s ({large['dataset']}, "
                  f"CatBoost on {crow[large['dataset']].get('clf_device')}), the faster device each, from {cvp_src}"]
    lines += [f"% {r['dataset']}: fit {r['fit_s']['median']} s, refit {r['refit_s']['median']} s "
              f"(magnification changed on {r['zoom_changed']} of {r['draws']} draws)" for r in ours]
    with open(os.path.join(OUT, "numbers_timing.tex"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines)); sys.exit(0)

for r in ours:                      # the file is the record; a hole in it must not become a macro
    for k in ("fit_s", "encode_ms", "image_to_mask_ms") + (() if OURS_SRC else ("bank_only_ms",)):
        if r.get(k) is None:
            sys.exit(f"REFUSING: {r['dataset']} has no {k}; a missing measurement would silently "
                     f"become a plausible macro")

fit_med_small = round(small["fit_s"]["median"])
fit_med_large = round(large["fit_s"]["median"])
fit_draw_lo = math.floor(min(r["fit_s"]["min"] for r in ours))
fit_draw_hi = math.ceil(max(r["fit_s"]["max"] for r in ours))
enc_lo = round(min(r["encode_ms"] for r in ours))
enc_hi = round(max(r["encode_ms"] for r in ours))
mask_lo = min(r["image_to_mask_ms"] for r in ours) / 1000
mask_hi = max(r["image_to_mask_ms"] for r in ours) / 1000

# Speed-up against nnU-Net at each end of the field range, floored so the claim understates itself.
ratio_lo = math.floor(nn["hrf"]["fit_s"] / large["fit_s"]["median"])
ratio_hi = math.floor(nn["dsb2018"]["fit_s"] / small["fit_s"]["median"])
bank_share = large["bank_only_ms"] / large["image_to_mask_ms"] if "bank_only_ms" in large else None

lines = [
    f"% Generated by scripts/make_timing_numbers.py from {OURS_SRC or SRC}"
    + (f" (nnU-Net from {SRC})" if OURS_SRC else "") + ". Do not hand-edit.",
    f"% Measured on one {'' if OURS_SRC else 'idle '}{src_ours['device']}, {src_ours['date']}.",
    f"\\newcommand{{\\fitSmall}}{{{fit_med_small}}}",
    f"\\newcommand{{\\fitLarge}}{{{fit_med_large}}}",
    f"\\newcommand{{\\fitDrawLo}}{{{fit_draw_lo}}}",
    f"\\newcommand{{\\fitDrawHi}}{{{fit_draw_hi}}}",
    f"\\newcommand{{\\encLo}}{{{enc_lo}}}",
    f"\\newcommand{{\\encHi}}{{{enc_hi}}}",
    f"\\newcommand{{\\maskLo}}{{{mask_lo:.2f}}}",
    f"\\newcommand{{\\maskHi}}{{{mask_hi:.1f}}}",
    f"\\newcommand{{\\encLargeS}}{{{large['encode_ms'] / 1000:.2f}}}",
    f"\\newcommand{{\\nnSmall}}{{{round(nn['dsb2018']['fit_s'] / 10) * 10}}}",
    f"\\newcommand{{\\nnLarge}}{{{round(nn['hrf']['fit_s'])}}}",
    f"\\newcommand{{\\costRatioLo}}{{{ratio_lo}}}",
    f"\\newcommand{{\\costRatioHi}}{{{ratio_hi}}}",
] + ([f"\\newcommand{{\\bankShareOfMask}}{{{bank_share:.2f}}}"] if bank_share is not None else [])
if CP_SRC:
    # Fine-tuned Cellpose-SAM against us on the same fields, floored so the ratio understates our advantage.
    cp = {r["dataset"]: r for r in json.load(open(CP_SRC))["rows"]}
    if small["dataset"] not in cp or large["dataset"] not in cp:
        sys.exit(f"REFUSING: Cellpose-SAM timing lacks {small['dataset']} or {large['dataset']}")
    cp_small, cp_large = cp[small["dataset"]]["fit_s"]["median"], cp[large["dataset"]]["fit_s"]["median"]
    lines += [f"\\newcommand{{\\cpFitSmall}}{{{math.floor(cp_small / 60)}}}",          # minutes, floored
              f"\\newcommand{{\\cpFitLarge}}{{{math.floor(cp_large / 60)}}}",
              f"\\newcommand{{\\cpRatioLo}}{{{math.floor(cp_large / large['fit_s']['median'])}}}",
              f"\\newcommand{{\\cpRatioHi}}{{{math.floor(cp_small / small['fit_s']['median'])}}}",
              f"% Cellpose-SAM fine-tune medians {cp_small:.0f} s ({small['dataset']}), {cp_large:.0f} s ({large['dataset']})"]
path = os.path.join(OUT, "numbers_timing.tex")
with open(path, "w") as fh:
    fh.write("\n".join(lines) + "\n")
print("\n".join(lines))
print(f"\nwrote {path}")
print(f"  nnU-Net at the largest field is a {nn['hrf']['bound']} bound, so {ratio_lo}x is a floor")
